"""Lossless row compression for Run's RGB565 backgrounds."""


def encode_row(row):
    output = bytearray()
    literals = []
    seen = {}

    def flush():
        if literals:
            output.append(len(literals) - 1)
            for value in literals:
                output.extend(value.to_bytes(2, 'little'))
            literals.clear()

    i = 0
    while i < len(row):
        best, distance = 0, 0
        for previous in seen.get(tuple(row[i:i + 3]), []):
            length = 3
            while length < 130 and i + length < len(row) and row[previous + length] == row[i + length]:
                length += 1
            if length > best:
                best, distance = length, i - previous
        if best >= 3:
            flush()
            output.extend((0x80 | (best - 3), distance))
            step = best
        else:
            literals.append(row[i])
            if len(literals) == 128:
                flush()
            step = 1
        for position in range(i, i + step):
            if position + 3 <= len(row):
                seen.setdefault(tuple(row[position:position + 3]), []).append(position)
        i += step
    flush()
    return output


def write_backgrounds(path, frames):
    data, offsets = bytearray(), []
    for frame in frames:
        assert len(frame) == 240 * 320
        for y in range(320):
            offsets.append(len(data))
            data.extend(encode_row(frame[y * 240:(y + 1) * 240]))
    offsets.append(len(data))
    lines = ['#pragma once', '#include <stdint.h>', '#include <pgmspace.h>',
             '// Generated by tools/build_run_scene.py; lossless row LZ.',
             f'constexpr uint8_t RUN_BACKGROUND_FRAME_COUNT = {len(frames)};',
             'const uint32_t run_background_offsets[] PROGMEM = {']
    for i in range(0, len(offsets), 12):
        lines.append('  ' + ', '.join(map(str, offsets[i:i + 12])) + ',')
    lines += ['};', 'const uint8_t run_background_data[] PROGMEM = {']
    for i in range(0, len(data), 24):
        lines.append('  ' + ', '.join(f'0x{x:02X}' for x in data[i:i + 24]) + ',')
    lines += ['};', '']
    path.write_text('\n'.join(lines))
